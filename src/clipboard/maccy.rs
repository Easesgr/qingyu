use std::collections::HashSet;
use std::path::{Path, PathBuf};

pub(crate) const STRING: &str = "public.utf8-plain-text";
pub(crate) const FILE_URL: &str = "public.file-url";
const HTML: &str = "public.html";
const RTF: &str = "public.rtf";
const LEGACY_FILES: &str = "NSFilenamesPboardType";
pub(crate) const HISTORY: &str = "com.qingyu.clipboard-history";
pub(crate) const MEDIA_PATH: &str = "com.qingyu.clipboard-media-path";
const SOURCE: &str = "org.nspasteboard.source";
const MAX_TEXT_BYTES: usize = 524_288;
const MAX_ITEMS: usize = 64;
// Clipboard.ignoredTypes union Defaults.ignoredPasteboardTypes, unchanged from upstream.
pub(crate) const IGNORED: &[&str] = &[
    "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
    "Pasteboard generator type", "com.agilebits.onepassword", "com.typeit4me.clipping",
    "de.petermaurer.TransientPasteboardType", "net.antelle.keeweb",
];
// PNG/TIFF/JPEG/HEIC are upstream defaults; the remaining formats are Qingyu additions.
const IMAGES: &[(&str, &str)] = &[
    ("public.png", "png"), ("public.tiff", "tiff"), ("public.jpeg", "jpg"), ("public.heic", "heic"),
    ("com.compuserve.gif", "gif"), ("org.webmproject.webp", "webp"), ("public.heif", "heif"),
    ("com.microsoft.bmp", "bmp"), ("public.avif", "avif"),
];

#[derive(Clone, Debug, PartialEq, Eq, serde::Deserialize)]
pub(crate) struct Metadata { pub change: i64, pub types: Vec<String>, pub items: Vec<Vec<String>> }
#[derive(Debug, PartialEq, Eq)]
pub(crate) enum Content { Text(String), Image { data: Vec<u8>, extension: String }, Files(Vec<PathBuf>) }
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum ReadError { Changed, Unavailable, TooLarge }
#[derive(Clone, Copy, Debug)]
pub(crate) struct ReadRequest<'a> {
    pub change: i64, pub item: Option<usize>, pub kind: &'a str, pub limit: usize, pub property_list: bool,
}
pub(crate) trait Pasteboard {
    fn change_count(&self) -> i64;
    fn metadata(&self) -> Result<Metadata, ReadError>;
    fn read(&self, request: ReadRequest<'_>) -> Result<Option<Vec<u8>>, ReadError>;
}

pub(crate) fn is_persistable(kind: &str) -> bool {
    !kind.starts_with("dyn.") && !kind.starts_with("com.microsoft.ole.source.") &&
        !matches!(kind, "com.apple.webarchive" | "Apple Web Archive pasteboard type")
}
fn is_enabled(kind: &str) -> bool {
    matches!(kind, STRING | FILE_URL | HTML | RTF | LEGACY_FILES) || IMAGES.iter().any(|(image, _)| *image == kind)
}
fn has(types: &[String], kind: &str) -> bool { types.iter().any(|value| value == kind) }
fn excluded(metadata: &Metadata) -> bool {
    // Board types can include private types missing from individual items (upstream #241).
    // Check item metadata too, before any values, to avoid partially recording a private multi-item copy.
    metadata.types.iter().chain(metadata.items.iter().flatten()).any(|kind| IGNORED.contains(&kind.as_str()))
}
fn replay(metadata: &Metadata) -> bool { has(&metadata.types, HISTORY) || metadata.items.iter().any(|types| has(types, HISTORY)) }

pub(crate) fn item_types(types: &[String]) -> HashSet<&str> {
    let mut selected: HashSet<_> = types.iter().map(String::as_str).filter(|kind| is_persistable(kind)).collect();
    // Don't request Word bookmarks/cross-references or their PDF preview (upstream #613/#770).
    if selected.contains("com.microsoft.Link-Source") && selected.contains("com.microsoft.ObjectLink") {
        for kind in ["com.microsoft.Link-Source", "com.microsoft.ObjectLink", "com.adobe.pdf"] { selected.remove(kind); }
    }
    selected
}

/// Metadata first, selected bytes second, metadata again. A racing read never consumes the new changeCount.
pub(crate) fn poll(board: &impl Pasteboard, previous: &mut i64, capture: bool) -> Option<Content> {
    let change = board.change_count();
    if change == *previous { return None; }
    if !capture { *previous = change; return None; }
    let metadata = board.metadata().ok()?;
    if metadata.change != change { return None; }
    let content = if excluded(&metadata) || replay(&metadata) { None } else {
        match collect(board, &metadata) { Ok(content) => content, Err(ReadError::TooLarge) => None, Err(_) => return None }
    };
    let after = board.metadata().ok()?;
    if after.change != change { return None; }
    *previous = change;
    if excluded(&after) || replay(&after) { None } else { content }
}

fn read(board: &impl Pasteboard, metadata: &Metadata, item: Option<usize>, kind: &str, limit: usize, property_list: bool) -> Result<Option<Vec<u8>>, ReadError> {
    board.read(ReadRequest { change: metadata.change, item, kind, limit, property_list })
}
fn collect(board: &impl Pasteboard, metadata: &Metadata) -> Result<Option<Content>, ReadError> {
    // Match upstream's supported/enabled guard before materializing any lazy provider.
    if !metadata.types.iter().any(|kind| is_enabled(kind)) { return Ok(None); }
    let selections: Vec<_> = metadata.items.iter().enumerate().filter_map(|(index, types)| {
        let types = item_types(types);
        types.iter().any(|kind| is_enabled(kind)).then_some((index, types))
    }).take(MAX_ITEMS).collect();

    let mut paths = Vec::new();
    for (index, types) in &selections {
        if !types.contains(FILE_URL) { continue; }
        if let Some(bytes) = read(board, metadata, Some(*index), FILE_URL, 16_384, false)? {
            if let Ok(value) = std::str::from_utf8(&bytes) {
                if let Ok(url) = url::Url::parse(value) {
                    if let Ok(path) = url.to_file_path() {
                        if path.as_os_str().len() <= 16_384 && !paths.contains(&path) { paths.push(path); }
                    }
                }
            }
        }
        if paths.len() >= super::MAX_FILES_PER_COPY { break; }
    }
    if paths.is_empty() && has(&metadata.types, LEGACY_FILES) {
        if let Some(bytes) = read(board, metadata, None, LEGACY_FILES, 131_072, true)? {
            if let Ok(legacy) = serde_json::from_slice::<Vec<PathBuf>>(&bytes) {
                for path in legacy {
                    if path.is_absolute() && path.as_os_str().len() <= 16_384 && !paths.contains(&path) { paths.push(path); }
                    if paths.len() >= super::MAX_FILES_PER_COPY { break; }
                }
            }
        }
    }
    if !paths.is_empty() { return Ok(Some(Content::Files(paths))); }

    // Read only actual item types. Aggregate/converted board types can trigger unrelated lazy providers (#241).
    for (kind, extension) in IMAGES {
        for (index, types) in &selections {
            if !types.contains(kind) { continue; }
            if let Some(data) = read(board, metadata, Some(*index), kind, super::MAX_IMAGE_BYTES as usize, false)? {
                if !data.is_empty() { return Ok(Some(Content::Image { data, extension: extension.to_string() })); }
            }
        }
    }
    // Merge explicit plain-text parts of multi-item copies (BBEdit/Edge, upstream #78/#472).
    // HTML/RTF without a plain representation are skipped: no background WebKit/HTML parsing or formatting storage.
    let mut strings = Vec::new(); let mut bytes = 0;
    for (index, types) in &selections {
        if !types.contains(STRING) { continue; }
        if let Some(data) = read(board, metadata, Some(*index), STRING, MAX_TEXT_BYTES, false)? {
            let Ok(text) = String::from_utf8(data) else { continue; };
            if text.trim().is_empty() || strings.contains(&text) { continue; }
            bytes += text.len() + usize::from(!strings.is_empty());
            if bytes > MAX_TEXT_BYTES { return Ok(None); }
            strings.push(text);
        }
    }
    Ok((!strings.is_empty()).then(|| Content::Text(strings.join("\n"))))
}

pub(crate) enum ReplayPaths { Active(Vec<PathBuf>), Empty, Unstable }
pub(crate) fn replay_paths(board: &impl Pasteboard) -> ReplayPaths {
    let Ok(metadata) = board.metadata() else { return ReplayPaths::Unstable; };
    if !replay(&metadata) { return ReplayPaths::Empty; }
    let mut paths = Vec::new();
    for (index, types) in metadata.items.iter().enumerate() {
        if !has(types, HISTORY) || !has(types, MEDIA_PATH) { continue; }
        match read(board, &metadata, Some(index), MEDIA_PATH, 16_384, false) {
            Ok(Some(bytes)) => if let Ok(path) = String::from_utf8(bytes).map(PathBuf::from) {
                if path.is_absolute() && !paths.contains(&path) { paths.push(path); }
            },
            Err(_) => return ReplayPaths::Unstable,
            _ => {},
        }
        if paths.len() >= super::MAX_FILES_PER_COPY { break; }
    }
    match board.metadata() {
        Ok(after) if after.change == metadata.change => if paths.is_empty() { ReplayPaths::Empty } else { ReplayPaths::Active(paths) },
        _ => ReplayPaths::Unstable,
    }
}

#[derive(Debug, serde::Serialize)]
pub(crate) struct WritePlan { pub items: Vec<WriteItem> }
#[derive(Debug, serde::Serialize)]
pub(crate) struct WriteItem {
    pub representations: Vec<Representation>,
    #[serde(skip_serializing_if = "Option::is_none")] pub lazy: Option<LazyFile>,
}
#[derive(Debug, serde::Serialize)]
pub(crate) struct Representation {
    #[serde(rename = "type")] pub kind: String,
    #[serde(skip_serializing_if = "Option::is_none")] pub text: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")] pub data: Option<String>,
}
#[derive(Debug, serde::Serialize)]
pub(crate) struct LazyFile { #[serde(rename = "type")] pub kind: String, pub path: PathBuf, pub max_bytes: u64 }
fn string(kind: &str, text: String) -> Representation { Representation { kind: kind.into(), text: Some(text), data: None } }
fn replay_item(representations: Vec<Representation>, path: Option<&Path>, lazy: Option<LazyFile>) -> WriteItem {
    let mut representations = representations;
    // Qingyu equivalents of Maccy's fromMaccy/source markers, in every item before atomic publication.
    representations.push(Representation { kind: HISTORY.into(), text: None, data: Some(String::new()) });
    representations.push(string(SOURCE, "com.qingyu".into()));
    if let Some(path) = path { representations.push(string(MEDIA_PATH, path.to_string_lossy().into_owned())); }
    WriteItem { representations, lazy }
}
pub(crate) fn text_plan(text: &str) -> WritePlan { WritePlan { items: vec![replay_item(vec![string(STRING, text.into())], None, None)] } }
pub(crate) fn image_plan(path: &Path) -> Option<WritePlan> {
    path.to_str()?; // Replay leases and native JSON paths must identify the same file without lossy conversion.
    let extension = path.extension()?.to_str()?.to_ascii_lowercase();
    let extension = match extension.as_str() { "jpeg" | "jpe" => "jpg", "tif" => "tiff", other => other };
    let (kind, _) = IMAGES.iter().find(|(_, image)| *image == extension)?;
    let url = url::Url::from_file_path(path).ok()?;
    Some(WritePlan { items: vec![replay_item(vec![string(FILE_URL, url.to_string())], Some(path), Some(LazyFile { kind: kind.to_string(), path: path.into(), max_bytes: super::MAX_IMAGE_BYTES }))] })
}
pub(crate) fn files_plan(paths: &[PathBuf]) -> Option<WritePlan> {
    if paths.is_empty() || paths.len() > super::MAX_FILES_PER_COPY { return None; }
    let items = paths.iter().map(|path| {
        path.to_str()?;
        let url = url::Url::from_file_path(path).ok()?;
        Some(replay_item(vec![string(FILE_URL, url.to_string())], Some(path), None))
    }).collect::<Option<Vec<_>>>()?;
    // Clipboard.copy uses writeObjects for file URLs so a selection remains separate, ordered pasteboard items.
    Some(WritePlan { items })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::cell::RefCell;
    use std::collections::HashMap;
    struct Board { metadata: RefCell<Metadata>, data: HashMap<(usize, String), Vec<u8>>, reads: RefCell<Vec<(usize, String)>>, race: bool }
    impl Board {
        fn new(items: &[&[&str]]) -> Self {
            let items: Vec<Vec<String>> = items.iter().map(|types| types.iter().map(|t| t.to_string()).collect()).collect();
            let types = items.iter().flatten().cloned().collect();
            Self { metadata: RefCell::new(Metadata { change: 42, types, items }), data: HashMap::new(), reads: RefCell::new(Vec::new()), race: false }
        }
        fn with(mut self, item: usize, kind: &str, value: &[u8]) -> Self { self.data.insert((item, kind.into()), value.to_vec()); self }
    }
    impl Pasteboard for Board {
        fn change_count(&self) -> i64 { self.metadata.borrow().change }
        fn metadata(&self) -> Result<Metadata, ReadError> { Ok(self.metadata.borrow().clone()) }
        fn read(&self, request: ReadRequest<'_>) -> Result<Option<Vec<u8>>, ReadError> {
            if self.metadata.borrow().change != request.change { return Err(ReadError::Changed); }
            let item = request.item.unwrap_or(usize::MAX); self.reads.borrow_mut().push((item, request.kind.into()));
            if self.race { self.metadata.borrow_mut().change += 1; return Err(ReadError::Changed); }
            Ok(self.data.get(&(item, request.kind.into())).filter(|bytes| bytes.len() <= request.limit).cloned())
        }
    }
    #[test]
    fn maccy_all_default_exclusions_apply_to_board_and_items_before_reads() {
        for marker in IGNORED {
            for board_only in [true, false] {
                let board = Board::new(&[&[STRING]]).with(0, STRING, b"private");
                if board_only { board.metadata.borrow_mut().types.push(marker.to_string()); }
                else { board.metadata.borrow_mut().items[0].push(marker.to_string()); }
                let mut previous = -1;
                assert_eq!(poll(&board, &mut previous, true), None, "{marker}, board_only={board_only}");
                assert_eq!(previous, 42); assert!(board.reads.borrow().is_empty());
            }
        }
    }
    #[test]
    fn maccy_supported_guard_and_persistable_filter_avoid_lazy_reads() {
        let unsafe_types = ["dyn.opaque", "com.microsoft.ole.source.bookmark", "com.apple.webarchive", "Apple Web Archive pasteboard type"];
        for kind in unsafe_types { assert!(!is_persistable(kind)); }
        let board = Board::new(&[&["com.apple.AnnotationKit.AnnotationItem"]]);
        assert_eq!(poll(&board, &mut -1, true), None); assert!(board.reads.borrow().is_empty());
        let board = Board::new(&[&[STRING, "dyn.opaque", "com.microsoft.ole.source.bookmark", "com.apple.webarchive"]]).with(0, STRING, b"safe");
        board.metadata.borrow_mut().types.push("public.png".into()); // Aggregate conversion type absent from the actual item (#241).
        assert_eq!(poll(&board, &mut -1, true), Some(Content::Text("safe".into())));
        assert_eq!(*board.reads.borrow(), vec![(0, STRING.into())]);
        let word: Vec<_> = [STRING, "com.microsoft.Link-Source", "com.microsoft.ObjectLink", "com.adobe.pdf"].into_iter().map(str::to_string).collect();
        assert_eq!(item_types(&word), HashSet::from([STRING]));
    }
    #[test]
    fn maccy_merges_plain_items_and_uses_plain_representation_without_html_parser() {
        let board = Board::new(&[&[STRING, HTML, RTF], &[STRING], &[STRING], &[HTML]])
            .with(0, STRING, b"first").with(1, STRING, b" \n ").with(2, STRING, b"second");
        assert_eq!(poll(&board, &mut -1, true), Some(Content::Text("first\nsecond".into())));
        assert!(board.reads.borrow().iter().all(|(_, kind)| kind == STRING));
        let rich_only = Board::new(&[&[HTML, RTF]]);
        assert_eq!(poll(&rich_only, &mut -1, true), None); assert!(rich_only.reads.borrow().is_empty());
    }
    #[test]
    fn maccy_file_selection_order_precedes_images_and_missing_file_data_falls_back() {
        let board = Board::new(&[&[FILE_URL, STRING, "public.png"], &[FILE_URL]])
            .with(0, FILE_URL, b"file:///tmp/first.png").with(1, FILE_URL, b"file:///tmp/second.mov");
        assert_eq!(poll(&board, &mut -1, true), Some(Content::Files(vec!["/tmp/first.png".into(), "/tmp/second.mov".into()])));
        assert!(board.reads.borrow().iter().all(|(_, kind)| kind == FILE_URL));
        let missing = Board::new(&[&[FILE_URL, STRING]]).with(0, STRING, b"available text");
        assert_eq!(poll(&missing, &mut -1, true), Some(Content::Text("available text".into())));
    }
    #[test]
    fn maccy_racing_or_disabled_snapshot_never_consumes_unread_copy() {
        let mut board = Board::new(&[&[STRING]]).with(0, STRING, b"old"); board.race = true;
        let mut previous = -1; assert_eq!(poll(&board, &mut previous, false), None);
        assert_eq!(previous, 42); assert!(board.reads.borrow().is_empty());
        previous = -1; assert_eq!(poll(&board, &mut previous, true), None); assert_eq!(previous, -1);
    }
    #[test]
    fn maccy_copy_plans_keep_multiple_files_ordered_and_mark_every_item() {
        let paths = vec![PathBuf::from("/tmp/one.png"), PathBuf::from("/tmp/two.mov")];
        let plan = files_plan(&paths).unwrap(); assert_eq!(plan.items.len(), 2);
        for (item, path) in plan.items.iter().zip(&paths) {
            assert_eq!(item.representations.iter().find(|r| r.kind == FILE_URL).unwrap().text, Some(url::Url::from_file_path(path).unwrap().to_string()));
            assert!(item.representations.iter().any(|r| r.kind == HISTORY));
            assert!(item.representations.iter().any(|r| r.kind == MEDIA_PATH && r.text.as_deref() == path.to_str()));
        }
        let image = image_plan(&paths[0]).unwrap(); assert_eq!(image.items[0].lazy.as_ref().unwrap().kind, "public.png");
        assert_eq!(image.items[0].lazy.as_ref().unwrap().max_bytes, super::super::MAX_IMAGE_BYTES);
    }
}
